export const getSuratName = (surat: number | string | undefined | null): string => {
  const numberValue = typeof surat === "string" ? parseInt(surat, 10) : Number(surat);
  if (!Number.isInteger(numberValue) || numberValue < 1 || numberValue > suratNames.length) {
    return surat == null ? "" : `Surat ${numberValue}`;
  }
  return suratNames[numberValue - 1];
};

export const suratOptions = suratNames.map((name, index) => ({
  value: index + 1,
  label: `${index + 1}. ${name}`,
}));
